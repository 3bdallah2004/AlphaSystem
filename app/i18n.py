def t(lang, key, **kwargs):
    ar, en = STRINGS[key]
    text = en if lang == "en" else ar
    return text.format(**kwargs) if kwargs else text


def case_type_label(lang, case_type):
    if case_type == ALL:
        return t(lang, "all_types")
    if lang == "en":
        return CASE_TYPE_EN.get(case_type, case_type)
    return case_type


def status_label(lang, status):
    return t(lang, "all_statuses") if status == ALL else t(lang, f"status_{status or 'draft'}")


def severity_label(lang, severity):
    if severity == ALL:
        return t(lang, "all_severities")
    return t(lang, f"sev_{severity}") if severity in SEVERITIES else "—"
